defmodule Game2048 do
  @moduledoc """
  ターミナルで遊ぶ 2048。

  ## ルール

  4×4 の盤面で、上下左右のどれかの方向にタイルをすべてスライドさせます。
  同じ数字のタイルがぶつかると、1つに合体して数字が2倍になります。
  1回動かすたびに、空いているマスに新しいタイル（2 か 4）が1つ出てきます。
  2048 のタイルを作れたら勝ち、どの方向にも動かせなくなったら負けです。

  ## 進め方

  内側（小さな部品）から外側（画面と入力）へ、6つのステップで作ります。
  各ステップのファイルに `TODO(human)` があり、使う文法の解説とやることを書いています。
  1ステップ終わるごとに、そのステップのテストだけを実行して確かめられます。

  | ステップ | ファイル | 内容 | テスト |
  |---|---|---|---|
  | 1 | `lib/game2048/row.ex` | 1行を左にスライドさせる（2048 の心臓部） | `mix test test/game2048/row_test.exs` |
  | 2 | `lib/game2048/board.ex` | 盤面を上下左右に動かす | `mix test test/game2048/board_test.exs` |
  | 3 | `lib/game2048/board.ex` | 空きマスにランダムなタイルを置く | 同上 |
  | 4 | `lib/game2048/board.ex`, `lib/game2048/game.ex` | 勝ち負けの判定 | `mix test test/game2048/game_test.exs` |
  | 5 | `lib/game2048/renderer.ex` | 盤面を文字列にする | `mix test test/game2048/renderer_test.exs` |
  | 6 | `lib/game2048/cli.ex`, `lib/mix/tasks/game2048.ex` | 入力を受け取って遊べるようにする | `mix test test/game2048/cli_test.exs` |

  全部できたら `mix game2048` で遊べます。

  ## 実装前の関数について

  まだ中身を書いていない関数は、`Game2048.todo!("ステップ1-1 compact/1", [row])` のような行で、
  「未実装」というエラーを出すようにしています。関数の中身を書いたら、この行は消してください。

  （2つ目の引数のリストは、まだ使っていない引数を渡しておくためのものです。
  これがないと、実装前の段階で「使っていない変数」などの警告がたくさん出て、本当のエラーが見つけにくくなります）

  全部のステップが終わったら、下の `todo!/2` 関数も消してかまいません。
  """

  # 未実装の関数から呼ぶ、「未実装」のエラーを出すための関数です。
  # raise を直接書くと、Elixir の型チェックが「この関数は必ずエラーになる」と判断して
  # 呼び出し側に大量の警告を出すため、apply/3 を通して型チェックの対象から外しています。
  @doc false
  def todo!(step, _args) do
    apply(:erlang, :error, [%RuntimeError{message: "TODO(human): " <> step}])
  end
end
